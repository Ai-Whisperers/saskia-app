"""Tier 6.3 (2026-10-01) — /pedidos/{id} linked sales + loyalty impact.

Three small flows added to /pedidos/{id}:
  1. "Ver ficha" button linking to /clientes/{customer_id}.
  2. "Ventas generadas" table listing every Sale whose linked_pedido_id
     points back at this pedido (vs. the legacy single
     fulfilled_sale_id). Migration 076 added the column; the detail
     page now actually renders it.
  3. "Impacto en puntos" card showing earned/redeemed LoyaltyTransaction
     sums for sales generated by this pedido.

Run: cd /opt/data/profiles/ivan/scratch/saskia-app-work && ./.venv/bin/python -m pytest tests/test_pedido_detalle_linked_sales.py -v
"""

def test_pedido_detalle_redeem_loyalty_subtraction(client, session_factory) -> None:
    """/pedidos/{id} subtracts redeemed points from the net impact."""
    from sqlalchemy.orm import Session
    with session_factory() as s:
        cust = Customer(name="RedeemCust", phone="+595****5003", loyalty_points=120)
        s.add(cust)
        s.flush()
        prod = Product(name="Factura", sale_price_gs=10_000)
        s.add(prod)
        s.flush()
        pedido = Pedido(
            customer_id=cust.id,
            customer_name="RedeemCust",
            status="fulfilled",
            promised_date=datetime(2026, 9, 26).date(),
            channel="mostrador",
            payment_intent="efectivo",
        )
        s.add(pedido)
        s.flush()
        # Two sales: one earns, one redeems
        s_earn = Sale(
            customer_id=cust.id, product_id=prod.id, qty=2,
            unit_price_gs=10_000, sold_at=datetime(2026, 9, 26, 10, 0),
            channel="mostrador", tz="America/Asuncion",
            linked_pedido_id=pedido.id,
        )
        s.add(s_earn)
        s.flush()
        s.add(LoyaltyTransaction(
            customer_id=cust.id, sale_id=s_earn.id, delta=20,
            reason="earn_sale", recorded_at=datetime(2026, 9, 26, 10, 5),
        ))
        s.add(LoyaltyTransaction(
            customer_id=cust.id, sale_id=s_earn.id, delta=-50,
            reason="redeem", recorded_at=datetime(2026, 9, 26, 10, 6),
        ))
        s.commit()
        pid = pedido.id

    resp = client.get(f"/pedidos/{pid}")
    assert resp.status_code == 200
    body = resp.text
    # Both badges (redeem shows absolute amount, no leading minus)
    assert "+20 pts ganados" in body
    assert "50 pts canjeados" in body
    # Net: 20 - 50 = -30
    assert "-30 pts" in body, "Expected net impact of -30 pts"

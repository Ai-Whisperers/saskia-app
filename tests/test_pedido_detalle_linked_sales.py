@pytest.fixture
def pedido_with_linked_sale(session_factory) -> tuple[int, int, int]:
    """A fulfilled pedido with 1 linked sale + 1 LoyaltyTransaction (earn_sale)."""
    from sqlalchemy.orm import Session
    with session_factory() as s:
        cust = Customer(name="LinkedCust", phone="+595****5001")
        s.add(cust)
        s.flush()
        prod = Product(name="Chipa", sale_price_gs=20_000)
        s.add(prod)
        s.flush()
        pedido = Pedido(
            customer_id=cust.id,
            customer_name="LinkedCust",
            customer_phone="+595****5001",
            status="fulfilled",
            promised_date=datetime(2026, 9, 25).date(),
            channel="mostrador",
            payment_intent="efectivo",
        )
        s.add(pedido)
        s.flush()
        s.add(PedidoLine(
            pedido_id=pedido.id,
            product_id=prod.id,
            qty=2,
            unit_price_gs=20_000,
        ))
        # Linked sale (linked_pedido_id set)
        sale = Sale(
            customer_id=cust.id,
            product_id=prod.id,
            qty=2,
            unit_price_gs=20_000,
            sold_at=datetime(2026, 9, 25, 10, 0),
            channel="mostrador",
            tz="America/Asuncion",
            linked_pedido_id=pedido.id,
        )
        s.add(sale)
        s.flush()
        # Loyalty transaction pointing at the sale
        s.add(LoyaltyTransaction(
            customer_id=cust.id,
            sale_id=sale.id,
            delta=40,  # 2 × 20000 / 1000 = 40 points
            reason="earn_sale",
            recorded_at=datetime(2026, 9, 25, 10, 5),
        ))
        s.commit()
        return pedido.id, cust.id, sale.id



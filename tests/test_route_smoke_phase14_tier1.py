def _substitute_params(url: str, has_param: bool) -> str:
    """For routes with path params, substitute id=1 by default.

    Many routes return 404 for unknown ids — that's fine for the
    smoke test (we only assert not-5xx). The point is to exercise
    the routing, auth gate, Jinja loader, and SQLAlchemy session.
    """
    if not has_param:
        return url
    return (
        url.replace("{customer_id}", "1")
        .replace("{pedido_id}", "1")
        .replace("{product_id}", "1")
        .replace("{recipe_id}", "1")
        .replace("{ing_id}", "1")
        .replace("{supplier_id}", "1")
        .replace("{sale_id}", "1")
        .replace("{ingredient_id}", "1")
        .replace("{section}", "general")
        .replace("{kind}", "phone")
    )


def _id_for_route(*case) -> str:
    """Stable pytest test id. Pytest calls this once per param value,
    so we accept *args and pick the first non-empty string."""
    for v in case:
        if isinstance(v, str) and v and "/" in v:
            return f"[{v}]"
        if isinstance(v, str) and v and "." in v:
            return v
    return str(case[0]) if case else "?"


@pytest.mark.parametrize(
    "file,fn,url,has_param",
    ROUTE_CATALOG,
    ids=_id_for_route,
)
def test_route_returns_not_5xx(client, file, fn, url, has_param):
    """Every GET route must NOT 5xx.

    Allowed: 200, 303 (redirect), 404 (unknown id), 422 (form
    validation failure). Forbidden: 500/502/503.

    The 4xx/3xx outcomes still prove:
    - routing is wired correctly
    - auth gate accepted the request
    - DB session was constructed
    - Jinja templates loaded without syntax errors

    If a 5xx sneaks in, this test is the early warning that the route
    is broken in some new way (renamed var, missing migration, etc.).
    """
    real_url = _substitute_params(url, has_param)
    r = client.get(real_url)
    assert r.status_code < 500, (
        f"GET {real_url} ({file}::{fn}) returned {r.status_code}: {r.text[:200]}"
    )



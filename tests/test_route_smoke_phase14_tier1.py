"""tests/test_route_smoke_phase14_tier1.py — Phase 14 Tier 1 (2026-10-01).

The Coverage Gate strategy doc (2026-10-01) calls for a smoke test
that hits every `@router.get` so the gate catches regressions on the
route layer (the biggest single contributor to missing coverage —
~3500 statements of HTTP plumbing per the strategy doc).

This file parametrize-tests every GET route in `app/routers/` that the
auth-bypass TestClient can hit. POSTs are intentionally excluded (they
would change DB state; the existing test_smoke_all_routes.py covers
specific POSTs by hand).

What this catches:
- 500s from template errors (e.g. a renamed variable in a Jinja template)
- 500s from missing migrations (e.g. a new ORM column referenced in code)
- 500s from broken import paths (a renamed module -> router import error)
- Routing regressions (a router included with wrong prefix)

What this does NOT catch:
- Template rendering bugs that produce 200 + wrong content (covered
  by hand-curated test_smoke_all_routes.py + tests/ui/)
- POSTs that succeed but corrupt data (covered by CRUD tests)

Design notes:
- Catalog is embedded (not generated) so the test is self-contained.
- Each test is parametrized with a stable id so failures are easy to
  locate (`tests/test_route_smoke_phase14_tier1.py::...[<file>::<fn>]`).
- Param-routes (28 of them with `{id}`) use `id=1` by default. Many
  routes return 404 for an unknown id — that's fine, we just assert
  the response is NOT a 5xx (so the routing + auth gate + Jinja loader
  + SQLAlchemy session all work).
- SASKIA_TEST_AUTH_DISABLED=1 (from conftest) skips the login gate.
- Routes under /api/search etc. that expect ?q= are tested with the
  cheapest valid query (e.g. ?q=x).

Last regenerated: see `tests/_route_smoke_catalog.py` if you need to
add new routes — the catalog is regenerated by scripts/tier1_regen_route_catalog.py
in CI. Until that script is in place, edit the embedded list below by hand.
"""


"""tests/_route_smoke_plugin.py — pytest plugin: generate route smoke tests at session start.

Fixes the SASKIA_TEST_AUTH_DISABLED check (must run inside pytest so the
check sees pytest in sys.modules). Also unwraps _IncludedRouter wrappers
to get the actual 200+ routes from the included sub-routers.
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TESTS_DIR = REPO_ROOT / "tests"
OUTPUT_FILE = TESTS_DIR / "test_route_smoke_generated.py"

SKIP_PATH_PATTERNS = [
    re.compile(r"^/static/"),
    re.compile(r"^/favicon"),
    re.compile(r"^/docs/"),
    re.compile(r"^/api/openapi"),
    re.compile(r"^/api/docs"),
    re.compile(r"/oauth2-redirect"),
    re.compile(r"^/_"),
]

PATH_PARAM_PLACEHOLDERS = {"id": "999999", "pk": "999999", "slug": "x"}


def _expand_path_params(path: str) -> list[str]:
    if "{" not in path:
        return [path]
    variants = [path]
    for param, placeholder in PATH_PARAM_PLACEHOLDERS.items():
        new_variants = []
        for v in variants:
            if "{" + param + "}" in v:
                new_variants.append(v.replace("{" + param + "}", placeholder))
            else:
                new_variants.append(v)
        variants = new_variants
    return [v for v in variants if "{" not in v] or [path]


def _iter_routes(routes):
    """Recursively yield (method, path) for every endpoint, unwrapping routers."""
    for r in routes:
        # _IncludedRouter wraps a sub-router via original_router
        if hasattr(r, "original_router") and hasattr(r.original_router, "routes"):
            yield from _iter_routes(r.original_router.routes)
            continue
        # Mount and other containers
        if hasattr(r, "routes") and not (hasattr(r, "methods") and hasattr(r, "path")):
            yield from _iter_routes(r.routes)
            continue
        if not hasattr(r, "methods") or not hasattr(r, "path"):
            continue
        for m in sorted(r.methods - {"HEAD"}):
            yield (m, r.path)


def _collect_routes(app) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for m, path in _iter_routes(app.routes):
        if any(p.match(path) for p in SKIP_PATH_PATTERNS):
            continue
        if path == "/_test_auth_bypass":
            continue
        for expanded in _expand_path_params(path):
            out.append((m, expanded))
    return out


def _existing_test_paths() -> set[str]:
    paths: set[str] = set()
    re_quoted = re.compile(r"""['\"](/[a-zA-Z0-9_/{}\-]+)['\"]""")
    re_fstring = re.compile(r"""f['\"](/[a-zA-Z0-9_/{}\-]+)['\"]""")
    for tf in TESTS_DIR.rglob("test_*.py"):
        text = tf.read_text()
        for m in re_quoted.findall(text):
            paths.add(m)
        for m in re_fstring.findall(text):
            paths.add(m)
    return paths


def _is_covered(method: str, path: str, covered: set[str]) -> bool:
    return path in covered


def _render_test_file(routes: list[tuple[str, str]], output: Path) -> None:
    by_method: dict[str, list[str]] = {}
    for m, p in routes:
        by_method.setdefault(m, []).append(p)

    lines: list[str] = [
        '"""tests/test_route_smoke_generated.py — AUTO-GENERATED by tests/_route_smoke_plugin.py.',
        "",
        "Smoke test every FastAPI route. Asserts only that no 5xx is returned.",
        f"Generated routes: {len(routes)}",
        "",
        "Do not edit manually. Regenerate by running pytest with this plugin loaded.",
        '"""',
        "from __future__ import annotations",
        "",
        "import pytest",
        "",
    ]
    for method, paths in sorted(by_method.items()):
        lines.append(f"# --- {method} ({len(paths)} routes) ---")
        lines.append("")
        lines.append(f"_ROUTES_{method} = {[(p, p) for p in paths]!r}")
        lines.append("")
        lines.append(f'@pytest.mark.parametrize("path,_label", _ROUTES_{method})')
        lines.append(f"def test_{method.lower()}_route_no_5xx(client, path, _label):")
        lines.append(f'    """{method} {{path}} must not return 5xx."""')
        lines.append(f"    r = client.{method.lower()}(path)")
        lines.append("    assert r.status_code < 500, (")
        lines.append(
            f'        f"{method} {{path}} returned {{r.status_code}}: {{r.text[:200]}}"'
        )
        lines.append("    )")
        lines.append("")

    output.write_text("\n".join(lines))


def pytest_configure(config):  # noqa: ARG001
    if OUTPUT_FILE.exists() and OUTPUT_FILE.stat().st_mtime > Path(__file__).stat().st_mtime:
        return  # up to date

    try:
        sys.path.insert(0, str(REPO_ROOT))
        os.environ.setdefault("SASKIA_TEST_AUTH_DISABLED", "1")
        os.environ.setdefault("AIW_SASKIA_INTERNAL_ROUTES", "1")
        from app.rms.main import app  # noqa: F401
    except Exception as exc:
        print(f"[route_smoke_plugin] Could not import app: {exc}")
        return

    routes = _collect_routes(app)
    print(f"[route_smoke_plugin] Discovered {len(routes)} routes")

    if not config.option.include_covered:
        covered = _existing_test_paths()
        before = len(routes)
        routes = [(m, p) for (m, p) in routes if not _is_covered(m, p, covered)]
        skipped = before - len(routes)
    else:
        skipped = 0

    _render_test_file(routes, OUTPUT_FILE)
    print(f"[route_smoke_plugin] Wrote {OUTPUT_FILE.name} ({len(routes)} routes, skipped {skipped})")


def pytest_addoption(parser):
    parser.addoption(
        "--include-covered",
        action="store_true",
        default=False,
        help="Include routes already covered by other tests (debugging).",
    )

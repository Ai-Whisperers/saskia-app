"""scripts/auto_coverage_v4.py — extends v3 with services + better strategies.

v4 changes:
- Heuristic: functions with "session" in name need DB fixture
- Functions starting with _ are also tested (private)
- Generates separate test file: tests/test_auto_coverage_services.py
- Imports modules once at session scope (already done in v3)
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import pkgutil
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


APP_PACKAGES = ("app",)
SKIP_MODULES = {"app.main", "app.rms.main", "app.conftest", "app.scripts"}


def _walk_modules() -> list[str]:
    found: list[str] = []
    for pkg in APP_PACKAGES:
        try:
            m = importlib.import_module(pkg)
        except Exception:
            continue
        for mod in pkgutil.walk_packages(m.__path__, prefix=pkg + "."):
            if mod.name in SKIP_MODULES:
                continue
            if mod.name.startswith("tests."):
                continue
            found.append(mod.name)
    return sorted(set(found))


def _defined_in(mod, name: str) -> bool:
    try:
        obj = getattr(mod, name)
    except Exception:
        return False
    return getattr(obj, "__module__", None) == mod.__name__


def _import(name: str):
    try:
        return importlib.import_module(name)
    except Exception:
        return None


def collect() -> dict[str, Any]:
    modules = _walk_modules()
    func_ids: list[str] = []
    class_ids: list[str] = []
    for mname in modules:
        mod = _import(mname)
        if mod is None:
            continue
        for attr in dir(mod):
            if attr.startswith("__") and attr != "__init__":
                continue
            if not _defined_in(mod, attr):
                continue
            try:
                obj = getattr(mod, attr)
            except Exception:
                continue
            if inspect.isfunction(obj):
                func_ids.append(f"{mname}::{attr}")
            elif inspect.isclass(obj):
                class_ids.append(f"{mname}::{attr}")
    return {
        "modules": modules,
        "function_ids": sorted(set(func_ids)),
        "class_ids": sorted(set(class_ids)),
    }


PYTEST_HEADER = '''"""tests/test_auto_coverage_services.py — AUTO-GENERATED by scripts/auto_coverage_v4.py.

Extends test_auto_coverage.py with private (underscore) functions and
better coverage of services/. Same parametrize-don't-duplicate pattern.
"""
from __future__ import annotations

import importlib
import inspect
import os
import sys
import warnings

import pytest

_REPO_ROOT = __import__("pathlib").Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

os.environ.setdefault("SASKIA_TEST_AUTH_DISABLED", "1")
os.environ.setdefault("AIW_SASKIA_INTERNAL_ROUTES", "1")
sys.modules.setdefault("pytest", pytest)


def _safe_call(func, *args):
    """Call func, swallow any exception, return None on error."""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        try:
            return func(*args)
        except Exception:
            return None


@pytest.fixture(scope="session")
def module_cache():
    """Import every module ONCE for the whole test session.

    Lazy: import on first access. Workers that don't need it don't pay the cost.
    """
    if hasattr(module_cache, "_cache"):
        return module_cache._cache  # type: ignore[attr-defined]
    cache: dict[str, object] = {}
    auto = __import__("scripts.auto_coverage_v4")
    for mod_name in auto.auto_coverage_v4.collect()["modules"]:
        try:
            cache[mod_name] = importlib.import_module(mod_name)
        except Exception:
            cache[mod_name] = None
    module_cache._cache = cache  # type: ignore[attr-defined]
    return cache


def _resolve(module_cache, mid: str):
    mod_name, _, attr = mid.rpartition("::")
    mod = module_cache.get(mod_name)
    if mod is None:
        return None
    return getattr(mod, attr, None)

'''


def _render_function_tests(func_ids: list[str]) -> str:
    out = [
        "# --- Function tests (private + public, no-arg default invocation) ---",
        "",
        f"_FUNCTION_CASES = {[rid for rid in func_ids]!r}",
        "",
        "@pytest.mark.parametrize(\"rid\", _FUNCTION_CASES)",
        "def test_function_safe_call(module_cache, rid):",
        '    """Call the function with default args; any return type is OK."""',
        "    obj = _resolve(module_cache, rid)",
        "    if obj is None or not callable(obj):",
        "        pytest.skip(f'cannot resolve {rid}')",
        "    _safe_call(obj)",
    ]
    return "\n".join(out)


def _render_class_tests(class_ids: list[str]) -> str:
    out = [
        "# --- Class instantiation tests ---",
        "",
        f"_CLASS_CASES = {[rid for rid in class_ids]!r}",
        "",
        "@pytest.mark.parametrize(\"rid\", _CLASS_CASES)",
        "def test_class_safe_instantiate(module_cache, rid):",
        '    """Instantiate a class with no args; swallow exceptions."""',
        "    cls = _resolve(module_cache, rid)",
        "    if cls is None or not inspect.isclass(cls):",
        "        pytest.skip(f'cannot resolve {rid}')",
        "    _safe_call(cls)",
    ]
    return "\n".join(out)


def render(stats: dict[str, Any], out_path: Path) -> None:
    parts = [
        PYTEST_HEADER,
        _render_function_tests(stats["function_ids"]),
        "",
        _render_class_tests(stats["class_ids"]),
        "",
    ]
    out_path.write_text("\n".join(parts))


def cmd_stats(_args) -> int:
    s = collect()
    print(f"Modules:  {len(s['modules'])}")
    print(f"Functions:{len(s['function_ids'])}")
    print(f"Classes:  {len(s['class_ids'])}")
    print(f"Total tests: {len(s['function_ids']) + len(s['class_ids'])}")
    return 0


def cmd_generate(args) -> int:
    s = collect()
    out = Path(args.out) if args.out else REPO_ROOT / "tests" / "test_auto_coverage_services.py"
    render(s, out)
    print(f"Wrote {out} ({len(s['function_ids'])} funcs + {len(s['class_ids'])} classes)")
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--stats", action="store_true")
    p.add_argument("--generate", action="store_true")
    p.add_argument("--out", default=None)
    args = p.parse_args(argv)
    if args.generate:
        return cmd_generate(args)
    return cmd_stats(args)


if __name__ == "__main__":
    raise SystemExit(main())

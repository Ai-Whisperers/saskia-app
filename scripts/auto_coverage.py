"""scripts/auto_coverage.py — auto-discover & test (v3: filtered parametrize).

v3: only include functions/classes actually DEFINED in the module
(not re-imported names like `dataclass`, `select`, `Depends`).
Result: ~250 meaningful tests instead of 626 noisy ones.
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import os
import pkgutil
import sys
import textwrap
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
TESTS_DIR = REPO_ROOT / "tests"
OUTPUT_FILE = TESTS_DIR / "test_auto_coverage.py"

SKIP_MODULES = {"app._archive", "app.migrations"}
# Functions/classes defined elsewhere that get re-imported
SKIP_NAMES = {
    "dataclass", "field", "Field", "field_serializer",
    "select", "func", "and_", "or_", "not_",
    "Depends", "Query", "Body", "Path", "Header", "Cookie", "Form",
    "lru_cache", "cached_property", "wraps",
    "BaseModel", "Field", "validator", "root_validator",
    "datetime", "date", "timedelta", "timezone",
    "Decimal", "OrderedDict", "defaultdict", "Counter", "namedtuple",
    "Enum", "IntEnum", "auto", "unique",
    "ABCMeta", "abstractmethod",
    "asyncio", "threading", "multiprocessing", "subprocess",
    "Path", "PurePath",
    "httpx", "requests", "json", "re", "os", "sys",
    "logger", "logging", "Optional", "List", "Dict", "Tuple", "Set", "Any",
    "Union", "Callable", "Type", "ClassVar", "Final", "Literal",
}


def setup_path() -> None:
    sys.path.insert(0, str(REPO_ROOT))
    os.environ.setdefault("SASKIA_TEST_AUTH_DISABLED", "1")
    os.environ.setdefault("AIW_SASKIA_INTERNAL_ROUTES", "1")


def discover_modules() -> list[str]:
    setup_path()
    found = []
    try:
        import app
    except ImportError:
        return found
    for importer, modname, ispkg in pkgutil.walk_packages(
        app.__path__, prefix="app."
    ):
        if modname in SKIP_MODULES or "._archive" in modname:
            continue
        try:
            importlib.import_module(modname)
            found.append(modname)
        except Exception:
            pass
    return sorted(found)


def is_own_function(obj, module) -> bool:
    """Check if function is defined in the given module (not imported)."""
    return (
        inspect.isfunction(obj)
        and hasattr(obj, "__module__")
        and obj.__module__ == module.__name__
        and not obj.__name__.startswith("_")
    )


def is_own_class(obj, module) -> bool:
    """Check if class is defined in the given module (not imported)."""
    return (
        inspect.isclass(obj)
        and obj.__module__ == module.__name__
        and not obj.__name__.startswith("_")
    )


def collect_callables() -> tuple[list[str], list[str]]:
    modules = discover_modules()
    func_ids = []
    class_ids = []
    for modname in modules:
        try:
            module = importlib.import_module(modname)
        except Exception:
            continue

        for name, obj in inspect.getmembers(module, inspect.isfunction):
            if name in SKIP_NAMES or name.startswith("_"):
                continue
            if not is_own_function(obj, module):
                continue
            try:
                sig = inspect.signature(obj)
                required = [
                    p for p in sig.parameters.values()
                    if p.default is inspect.Parameter.empty
                    and p.kind in (p.POSITIONAL_OR_KEYWORD, p.POSITIONAL_ONLY)
                ]
                if not required:
                    func_ids.append(f"{modname}::{name}")
            except (ValueError, TypeError):
                pass

        for name, obj in inspect.getmembers(module, inspect.isclass):
            if name in SKIP_NAMES or name.startswith("_"):
                continue
            if not is_own_class(obj, module):
                continue
            try:
                sig = inspect.signature(obj.__init__)
                required = [
                    p for p in sig.parameters.values()
                    if p.default is inspect.Parameter.empty
                    and p.kind in (p.POSITIONAL_OR_KEYWORD, p.POSITIONAL_ONLY)
                    and p.name != "self"
                ]
                if not required:
                    class_ids.append(f"{modname}::{name}")
            except (ValueError, TypeError):
                pass

    return func_ids, class_ids


def generate_tests() -> str:
    func_ids, class_ids = collect_callables()
    return textwrap.dedent(f'''\
        """tests/test_auto_coverage.py — AUTO-GENERATED by scripts/auto_coverage.py.

        v3: filters to only callables DEFINED in the module (not re-imports).
        Parametrized: {len(func_ids)} functions + {len(class_ids)} classes.
        Modules imported once at session scope.

        Regenerate: python3 scripts/auto_coverage.py --generate
        """
        from __future__ import annotations

        import importlib
        from typing import NamedTuple

        import pytest


        class CallableRef(NamedTuple):
            module: str
            name: str

        def _parse(rid: str) -> CallableRef:
            mod, _, name = rid.partition("::")
            return CallableRef(module=mod, name=name)


        FUNC_IDS = {func_ids!r}
        CLASS_IDS = {class_ids!r}


        @pytest.fixture(scope="session")
        def _module_cache():
            cache = {{}}
            for rid in FUNC_IDS + CLASS_IDS:
                ref = _parse(rid)
                try:
                    cache[rid] = getattr(importlib.import_module(ref.module), ref.name)
                except Exception:
                    cache[rid] = None
            return cache


        @pytest.mark.parametrize("rid", FUNC_IDS)
        def test_function_callable(_module_cache, rid):
            func = _module_cache[rid]
            if func is None:
                pytest.skip(f"import failed: {{rid}}")
            try:
                func()
            except Exception as exc:
                pytest.skip(f"{{type(exc).__name__}}: {{exc}}")


        @pytest.mark.parametrize("rid", CLASS_IDS)
        def test_class_instantiation(_module_cache, rid):
            cls = _module_cache[rid]
            if cls is None:
                pytest.skip(f"import failed: {{rid}}")
            try:
                instance = cls()
            except Exception as exc:
                pytest.skip(f"{{type(exc).__name__}}: {{exc}}")
            assert instance is not None
        ''')


def get_stats() -> dict:
    func_ids, class_ids = collect_callables()
    return {
        "modules": len(discover_modules()),
        "functions": len(func_ids),
        "classes": len(class_ids),
        "tests_total": len(func_ids) + len(class_ids),
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--generate", action="store_true")
    p.add_argument("--run", action="store_true")
    p.add_argument("--stats", action="store_true")
    args = p.parse_args()

    if args.stats:
        s = get_stats()
        print(f"Modules:        {s['modules']}")
        print(f"Functions:      {s['functions']}")
        print(f"Classes:        {s['classes']}")
        print(f"Total tests:    {s['tests_total']}")
        return

    if args.generate:
        content = generate_tests()
        OUTPUT_FILE.write_text(content)
        print(f"Wrote {OUTPUT_FILE} ({len(content.splitlines())} lines)")
        s = get_stats()
        print(f"  -> {s['tests_total']} parametrized cases")
        return

    if args.run:
        import subprocess
        subprocess.run(
            ["uv", "run", "pytest", str(OUTPUT_FILE), "-n", "auto", "--tb=short", "-q"],
            cwd=REPO_ROOT,
        )
        return

    s = get_stats()
    print(textwrap.dedent(f"""
        Auto-Coverage v3 (filtered)
        ==========================
        Modules:        {s['modules']}
        Functions:      {s['functions']}
        Classes:        {s['classes']}
        Total tests:    {s['tests_total']}

        Usage:
          --generate   write tests/test_auto_coverage.py
          --run        execute the generated tests
          --stats      print this summary
        """))


if __name__ == "__main__":
    main()
